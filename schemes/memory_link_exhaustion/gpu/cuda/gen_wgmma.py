"""Generate wgmma.h: m64nNk16 bf16->f32 SS wrappers (K-major A and B) for several N."""
import sys

def gen(n):
    r = n // 2
    regs = ", ".join(f"%{i}" for i in range(r))
    outs = ", ".join(f'"+f"(d[{i}])' for i in range(r))
    return f'''
__device__ __forceinline__ void wgmma_n{n}(float (&d)[{r}], uint64_t da, uint64_t db, int scale_d) {{
  asm volatile("{{\\n.reg .pred p;\\nsetp.ne.b32 p, %{r + 2}, 0;\\n"
    "wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16 {{{regs}}}, %{r}, %{r + 1}, p, 1, 1, 0, 0;\\n}}\\n"
    : {outs}
    : "l"(da), "l"(db), "r"(scale_d));
}}
'''

out = ["// generated by gen_wgmma.py\n#pragma once\n#include <cstdint>\n"]
for n in (16, 32, 64, 128, 256):
    out.append(gen(n))
# write only on change: rewriting the header bumps its mtime, ninja then relinks the .so in place,
# and a process that already has it mapped (CUDA lazy-loads kernel images from it) gets garbage
path = sys.argv[1] if len(sys.argv) > 1 else "wgmma.h"
txt = "".join(out)
try:
    same = open(path).read() == txt
except OSError:
    same = False
if not same:
    open(path, "w").write(txt)
